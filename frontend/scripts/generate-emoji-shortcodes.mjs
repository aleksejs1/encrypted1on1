/**
 * Names are not checked against the tokenizer's pattern here: a test in markdown.test.ts holds the
 * generated table to `EMOJI_SHORTCODE_NAME`, the one copy of it.
 */
function buildTable() {
  const table = new Map();
  const add = (name, emoji) => {
    if (table.has(name)) {
      throw new Error(`"${name}" is listed twice`);
    }
    table.set(name, emoji);
  };
  for (const { emoji, names } of gemoji) {
    for (const name of names) {
      add(name, emoji);
    }
  }
  for (const [slackName, githubName] of Object.entries(SLACK_ALIASES)) {
    const emoji = table.get(githubName);
    if (!emoji) {
      throw new Error(`"${githubName}" is not a GitHub shortcode`);
    }
    add(slackName, emoji);
  }
  return [...table].sort(([a], [b]) => (a < b ? -1 : 1));
}

async function render() {
  const entries = buildTable()
    .map(
      ([name, emoji]) => `[${JSON.stringify(name)}, ${JSON.stringify(emoji)}],`,
    )
    .join('\n');
  const source = `// Generated by scripts/generate-emoji-shortcodes.mjs. Do not edit by hand: change the script
// and re-run it.

/**
 * Emoji shortcode names (GitHub's, plus the common Slack ones) and the character each stands
 * for. A \`Map\`, not an object, so a name like \`constructor\` finds nothing.
 */
export const EMOJI_SHORTCODES: ReadonlyMap<string, string> = new Map([
${entries}
]);
`;
  const options = await prettier.resolveConfig(OUTPUT);
  return prettier.format(source, { ...options, filepath: OUTPUT });
}

const expected = await render();
if (process.argv.includes('--check')) {
  const actual = await readFile(OUTPUT, 'utf8').catch(() => '');
  if (actual !== expected) {
    console.error(
      'src/anketa/emojiShortcodes.ts is out of date. Run: npm run emoji-shortcodes',
    );
    process.exit(1);
  }
} else {
  await writeFile(OUTPUT, expected);
}
